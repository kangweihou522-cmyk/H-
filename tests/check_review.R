suppressPackageStartupMessages({library(jsonlite);library(GO.db);library(fgsea)})
source('/project/scripts/enrichment.R')
cfg<-list(min_set=1,max_set=100)
sets<-list(BP_A=c('g1','g2'),BP_B=c('g3','g4'),CC_A=c('g1','g5'))
ont<-c(BP_A='BP',BP_B='BP',CC_A='CC');desc<-setNames(names(sets),names(sets))
x<-ora(sets,desc,paste0('g',1:10),c('g1','g5'),ont,cfg)
stopifnot(all(x$background[x$ontology=='BP']==4),all(x$selected[x$ontology=='BP']==1))
stopifnot(all(x$background[x$ontology=='CC']==2),all(x$selected[x$ontology=='CC']==2))
expected<-phyper(1-1,2,4-2,1,lower.tail=FALSE)
stopifnot(x$pvalue[x$term=='BP_A']==expected)
stopifnot(all.equal(x$padj[x$ontology=='BP'],p.adjust(x$pvalue[x$ontology=='BP'],'BH')))
# The filtered non-finite duplicate must not mask a valid lower-expression ID.
r<-data.frame(gene=c('E1.1','E1.2','E2.1'),baseMean=c(100,50,20),stat=c(NA,3,-1),significant=c(FALSE,TRUE,FALSE),log2FoldChange=c(NA,2,-1))
annotation<-list(mapped=data.frame(gene=r$gene,id=c('E1','E1','E2'),symbol=c('S1','S1','S2'),entrez=c('1','1','2')),go=list(),go_desc=character(),ontology=character(),gmt=list(),gmt_desc=character())
path<-tempfile();dir.create(path);run_enrichment(r,annotation,path,list(gmt_id='ENSEMBL',min_set=1,max_set=100,permutations=100))
ranks<-read.csv(file.path(path,'gsea-ranks.csv'))
stopifnot(identical(ranks$gene,c('E1','E2')),identical(ranks$stat,c(3L,-1L)))
unlink(path,recursive=TRUE)
cat('PASS: per-ontology GO background / selection / BH; finite-ID collapse\n')
source('/project/scripts/mining.R')
f<-data.frame(Power=c(2,4,6,8),SFT.R.sq=c(.91,.82,.9,NA),slope=c(2,-2,-2,-3))
stopifnot(select_soft_power(f,'auto',10)==6,select_soft_power(f,'manual',10)==10)
stopifnot(is.na(select_soft_power(f[1:2,],'auto',6)))
cat('PASS: automatic power rejects positive slopes / missing fit; manual choice preserved\n')
path<-tempfile();dir.create(path)
modules<-data.frame(gene=paste0('g',1:6),module=c('blue','blue','green','green','grey','grey'),kME=1)
norm<-matrix(10:21,nrow=6,dimnames=list(modules$gene,c('S1','S2')))
a<-list(mapped=data.frame(gene=modules$gene,id=modules$gene),go=sets,go_desc=desc,ontology=ont,gmt=list(),gmt_desc=character())
module_enrichment(modules,norm,a,path,list(gmt_id='ENSEMBL',min_set=1,max_set=100))
out<-read.csv(file.path(path,'wgcna-module-enrichment.csv'))
stopifnot(!any(out$module=='grey'),all(out$background[out$ontology=='BP']==4),all(out$background[out$ontology=='CC']==2))
bp<-out[out$ontology=='BP',];stopifnot(all.equal(bp$padj,p.adjust(bp$pvalue,'BH')))
unlink(path,recursive=TRUE)
cat('PASS: module enrichment uses network universe and BH across module x term per ontology\n')
m<-data.frame(sample=c('001','002','003','004'),group=factor(c('C','C','T','T')),score=c('1.1','2.2','3.3','4.4'))
t<-trait_matrix(m,list('score'))
stopifnot(identical(rownames(t),m$sample),identical(unname(t[,'score']),c(1.1,2.2,3.3,4.4)))
cat('PASS: character metadata retains sample IDs; numeric traits retain continuous scale\n')
